  const patterns = [
    [/^([0-9]+) 项身体测量$/, (_, n) => n + ' tests'],
    [/^全选 · (\d+) 项$/, (_, n) => 'Select all · ' + n],
    [/^保存计划 · (\d+) 项$/, (_, n) => 'Save plan · ' + n],
    [/^步骤 (.+)$/, (_, n) => 'Step ' + n],
    [/^第 (.+) 页 · 示例$/, (_, n) => 'Page ' + n + ' · Sample'],
    [/^设备编号：(.+)$/, (_, id) => 'Device ID ' + id],
    [/^当前报告 (v\d+)$/, (_, version) => 'Report ' + version],
    [/^领取状态：(.+)$/, (_, status) => 'Collection · ' + english(status)],
    [/^已完成 (\d+) 项。(?:部分完成 (\d+) 项。)?(?:未取得结果 (\d+) 项。)?(当前离线。)?$/, (_, done, partial, missing, offline) =>
      [done + ' complete', partial && partial + ' partly complete', missing && missing + ' without results', offline && 'Offline'].filter(Boolean).join(' · ')],
    [/^网络：(.+)$/, (_, status) => 'Wi-Fi · ' + english(status)],
    [/^人体成分 \/ (v\d+)$/, (_, v) => 'Body composition / ' + v],
    [/^最近状态事件 · (\d+) 条$/, (_, n) => 'Recent demo events · ' + n],
    [/^· (.+)$/, (_, label) => '· ' + english(label)]
  ];
  const containsChinese = /[\u3400-\u9fff]/;

  function english(value) {
    const label = value.trim();
    if (!containsChinese.test(label)) return value;
    if (Object.hasOwn(copy, label)) return value.replace(label, copy[label]);
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(label)) return value.replace(label, label.replace(pattern, replacement));
    }
    const parts = label.split(/(\s+[·/]\s+|,\s+)/);
    if (parts.length === 1) return value;
    return value.replace(label, parts.map(english).join(''));
  }

  function surface(node) {
    if (!node) return;
    const walker = node.ownerDocument.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    for (let word = walker.nextNode(); word; word = walker.nextNode()) {
      const value = word.parentElement?.matches('.scroll-pre')?
        word.textContent.split('\n').map(eventLine).join('\n'):english(word.textContent);
      if (value !== word.textContent) word.textContent = value;
    }
    const attributes = ['aria-label', 'aria-description', 'alt', 'title', 'placeholder'];
    for (const element of [node, ...node.querySelectorAll(attributes.map(name => '[' + name + ']').join(','))]) {
      for (const name of attributes) {
        if (element.hasAttribute?.(name)) element.setAttribute(name, english(element.getAttribute(name)));
      }
    }
  }

  function eventLine(line) {
    const match = line.match(/^(\d{2}:\d{2}:\d{2}) (\S+) ?(.*)$/);
    if (!match) return line;
    const [, time, event, detail] = match;
    let copy = english(detail);
    if (detail.startsWith('{')) {
      try {
        copy = JSON.stringify(JSON.parse(detail), (_, value) => typeof value === 'string' ? english(value) : value);
      } catch {
        // Keep the original event detail if it is not structured.
      }
    }
    return [time, english(event), copy].filter(Boolean).join(' ');
  }

  root.ANOVATOR_REVIEW_EN = { text: english, surface };
